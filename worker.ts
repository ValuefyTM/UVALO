// Worker entry: the Next.js app (OpenNext), behind a small layer that
//  - sends pages opened on an old domain (tools.valuefy.ro) to the same page on the app's domain (app.uvalo.ro), with a
//    301 that keeps the path and the query (sign-in links and invitations already sent keep working). /api/ stays
//    reachable on the old domain, so other apps (the CRM's parcel centres) and pending requests are not broken;
//  - drops client-sent forwarding headers, so links in emails are built only from the real Host.
//  - serves the presentation site on the bare brand domain (uvalo.ro, www.uvalo.ro): "/" is the app's /site page, the
//    files that page needs pass through, and every other path goes to the same path in the app with a temporary 302
//    (uvalo.ro/login → app.uvalo.ro/login);
//  - serves the phone app (PWA) on inspectii.uvalo.ro: "/" is /m, /sw.js and /manifest.webmanifest at the root, /api/ and
//    the app files pass through, any other path goes back to "/";
// OLD_HOSTS, SITE_HOSTS, INSP_HOSTS (comma-separated) and APP_URL can change the domains without touching the code.
// @ts-expect-error generated by `opennextjs-cloudflare build`
import { default as app } from "./.open-next/worker.js";

// @ts-expect-error generated by `opennextjs-cloudflare build`
export { DOQueueHandler, DOShardedTagCache, BucketCachePurge } from "./.open-next/worker.js";

type Env = { OLD_HOSTS?: string; SITE_HOSTS?: string; INSP_HOSTS?: string; APP_URL?: string } & Record<string, unknown>;

/** What the presentation site loads from the app: its pictures, the Next.js scripts and styles, logo, icons. */
const SITE_FILES = /^\/(_next\/|fonts\/|site\/|word\/prezentare\/|uvalo-[a-z-]+\.svg$|icon\.svg$|favicon\.ico$|og-uvalo\.jpg$)/;

/** The phone app's domain (inspectii.uvalo.ro): "/" is the app (/m), plus its service worker and manifest at the root. */
const INSP_PATHS: Record<string, string> = { "/": "/m", "/sw.js": "/api/m/sw", "/manifest.webmanifest": "/api/m/manifest" };
const INSP_FILES = /^\/(api\/|_next\/|fonts\/|loc-icon-[a-z0-9-]+\.png$|uvalo-[a-z-]+\.svg$|icon\.svg$|favicon\.ico$)/;

function clean(req: Request) {
  const headers = new Headers(req.headers);
  headers.delete("x-forwarded-host");
  headers.delete("x-forwarded-proto");
  return new Request(req, { headers });
}

const hosts = (v: string) => v.split(",").map((h) => h.trim().toLowerCase()).filter(Boolean);

/**
 * The schedule (wrangler "triggers": every 15 minutes): the phone reminders of Inspecții, sent by the app's /api/m/cron.
 * The call carries a key kept in the database (app_settings "cron_key", made on the first run), so nobody else can trigger it.
 */
async function cron(env: Env, ctx: ExecutionContext) {
  const db = env.DB as D1Database | undefined;
  if (!db) return;
  let row = await db.prepare("SELECT value FROM app_settings WHERE key = 'cron_key'").first<{ value: string }>();
  if (!row) {
    const k = [...crypto.getRandomValues(new Uint8Array(24))].map((b) => b.toString(16).padStart(2, "0")).join("");
    await db.prepare("INSERT OR IGNORE INTO app_settings (key, value, updated_at) VALUES ('cron_key', ?, ?)").bind(JSON.stringify(k), new Date().toISOString()).run();
    row = await db.prepare("SELECT value FROM app_settings WHERE key = 'cron_key'").first<{ value: string }>();
  }
  const base = (env.APP_URL || "https://app.uvalo.ro").replace(/\/$/, "");
  await app.fetch(new Request(`${base}/api/m/cron`, { method: "POST", headers: { "x-cron-key": JSON.parse(row!.value) } }), env, ctx);
}

export default {
  async scheduled(_event: ScheduledController, env: Env, ctx: ExecutionContext) {
    ctx.waitUntil(cron(env, ctx));
  },
  async fetch(req: Request, env: Env, ctx: ExecutionContext) {
    const url = new URL(req.url);
    const host = url.hostname.toLowerCase();
    const to = (env.APP_URL || "https://app.uvalo.ro").replace(/\/$/, "");
    if (hosts(env.SITE_HOSTS ?? "uvalo.ro,www.uvalo.ro").includes(host)) {
      if (url.pathname === "/") return app.fetch(new Request(new URL(`/site${url.search}`, url), clean(req)), env, ctx);
      if (!SITE_FILES.test(url.pathname)) return Response.redirect(`${to}${url.pathname}${url.search}`, 302);
    }
    if (hosts(env.INSP_HOSTS ?? "inspectii.uvalo.ro").includes(host)) {
      const p = url.pathname, inner = INSP_PATHS[p];
      if (inner) return app.fetch(new Request(new URL(`${inner}${p === "/" ? url.search : ""}`, url), clean(req)), env, ctx);
      if (!INSP_FILES.test(p)) return Response.redirect(new URL(`/${url.search}`, url).toString(), 302);
    }
    if (hosts(env.OLD_HOSTS || "tools.valuefy.ro").includes(host) && !url.pathname.startsWith("/api/")) {
      return Response.redirect(`${to}${url.pathname}${url.search}`, 301);
    }
    return app.fetch(clean(req), env, ctx);
  },
};
